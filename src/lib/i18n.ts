export function t(lang: Lang, key: keyof TranslationKeys): string {
  return translations[lang][key] || translations.en[key];
}

export function pickLang(lang: Lang, en: string, cy?: string): string;
export function pickLang<T>(lang: Lang, values: Partial<Record<Lang, T>>, fallback: T): T;
export function pickLang<T>(lang: Lang, enOrValues: string | Partial<Record<Lang, T>>, cyOrFallback?: T | string): T | string {
  if (typeof enOrValues === "string") {
    // Old style: pickLang(lang, "english", "welsh")
    if (lang === "cy" && cyOrFallback) return cyOrFallback as string;
    return enOrValues;
  }
  // New style: pickLang(lang, { en: "...", cy: "..." }, fallback)
  const values = enOrValues as Partial<Record<Lang, T>>;
  return values[lang] ?? values.en ?? (cyOrFallback as T);
}